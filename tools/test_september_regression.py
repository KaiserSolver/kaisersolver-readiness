"""September regression: the published 2026-09-14 readiness screens, rebuilt from their own evidence.

build_report.py's path (rows -> window -> rebuild_state -> the tool's readiness_report) is replayed over each
run's evidence and its screen is compared with the one in runs/<chain>/2026-09-14/report.md. Those reports were
generated by a private script (its sha256 is in run.json) with two rules this generator does not use by default:

* an auction replayed more than once kept its LAST replay (`--keep last` here);
* the field counters summed the `_meta` of the cycles with to_block <= hi and from_block >= lo - 2000, without
  clipping unscanned blocks to the window, and "auctions formed" was the attempted count.

With both rules the rebuilt screens are byte-identical to the published ones. With this generator's own field
counters (every cycle touching the window, unscanned blocks clipped to it, the tool's auctions_formed) only the
field lines move, by the amounts pinned below; with the default `--keep first` the per-auction figures move too.

Needs the evidence, which is not public: READINESS_EVIDENCE_ROOT laid out as each run's EVIDENCE.sha256 names it,
and cow-backtester 0.11.0, the version that scored those rows. Skipped otherwise (CI has neither).
"""

from __future__ import annotations

import difflib
import functools
import json
import os
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import pytest

ROOT_ENV = "READINESS_EVIDENCE_ROOT"
SEPTEMBER_TOOL = "0.11.0"
EVIDENCE_ROOT = Path(os.environ[ROOT_ENV]) if os.environ.get(ROOT_ENV) else None
if EVIDENCE_ROOT is None:
    pytest.skip(f"{ROOT_ENV} is not set (the 2026-09-14 evidence is not public)", allow_module_level=True)
bt = pytest.importorskip("cow_backtester.backtest")
if bt.VERSION != SEPTEMBER_TOOL:
    pytest.skip(f"the published screens were scored by cow-backtester {SEPTEMBER_TOOL}, {bt.VERSION} is installed",
                allow_module_level=True)

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_report  # noqa: E402
import rebuild_state  # noqa: E402
import record  # noqa: E402

RECORD = HERE.parent
CHAINS = ["arbitrum-one", "base", "bnb"]
OWN = {
    "arbitrum-one": "0xdd5aecdd8ba8498706e2583f6e2ff90e08e1c01b",
    "base": "0x4c7bdd2d75050c4fdb84ad47dd328dc5c07d7743",
    "bnb": "0x4914895fe025d44b2fafbe65f7d988c6ef0c1378",
}
# (settlements found, auctions formed, excluded, unscanned blocks) under this generator's field rule
GENERATOR_FIELD = {
    "arbitrum-one": (1096, 1051, 30, 0),
    "base": (2510, 2251, 36, 0),
    "bnb": (6727, 6159, 659, 3613),
}
# what the published September rule gave, for the record (the screens carry them)
SEPTEMBER_FIELD = {
    "arbitrum-one": (1094, 1030, 30, 0),
    "base": (2507, 2098, 36, 0),
    "bnb": (6949, 5970, 717, 4246),
}
# bids (auctions with >= 1 solution) under the default --keep first; the published figures kept the last replay
BIDS_KEEP_FIRST = {"arbitrum-one": 489, "base": 984, "bnb": 1420}
FIELD_LINE_MARKERS = ("settlements found", "excluded ", "[WARN] scan coverage", "[PASS] scan coverage", "field coverage")


def run_json(chain: str) -> dict[str, Any]:
    return json.loads((RECORD / "runs" / chain / "2026-09-14" / "run.json").read_text())


def published_screen(chain: str) -> str:
    lines = (RECORD / "runs" / chain / "2026-09-14" / "report.md").read_text().split("\n")
    start = lines.index("```")
    return "\n".join(lines[start + 1 : lines.index("```", start + 1)])


@functools.cache
def inputs(chain: str, keep: str) -> tuple[Any, Any]:
    assert EVIDENCE_ROOT is not None
    run = run_json(chain)
    argv = [
        "--chain", chain, "--from-block", str(run["window"]["from_block"]), "--to-block", str(run["window"]["to_block"]),
        "--compete", "--solver-url", f"http://127.0.0.1:11090/prod/{chain}", "--engine-sha", run["engine"]["build_sha"],
        "--own-address", OWN[chain], "--manifest", str(EVIDENCE_ROOT / run["body_archive_manifest"]["path"]),
        "--keep", keep, "--out-dir", "unused",
    ]  # fmt: skip
    for e in run["evidence"]:
        if e["kind"] == "rows":
            argv += ["--rows", str(EVIDENCE_ROOT / e["path"])]
    a = build_report.build_parser().parse_args(argv)
    return a, build_report.load_inputs(a)


def state_dict(chain: str, keep: str) -> dict[str, Any]:
    a, inp = inputs(chain, keep)
    native = str(bt.CHAINS.get(chain, {}).get("native", "ETH"))
    return rebuild_state.build_state(inp.windowed.rows, inp.cycles, inp.window, a.solver_name, native).to_dict()


def screen(chain: str, keep: str, st: dict[str, Any]) -> tuple[dict[str, Any], str]:
    a, inp = inputs(chain, keep)
    max_auctions = max((c.max_auctions for c in inp.cycles.kept), default=0)
    return build_report.run_readiness(st, build_report.readiness_args(a, inp.facts, max_auctions))


def field_counts(st: dict[str, Any]) -> tuple[int, int, int, int]:
    unscanned = sum(b - a + 1 for a, b in st["failed_ranges"])
    return len(st["txs"]), st["n_found"], sum(st["skip"].values()), unscanned


def with_september_field_rule(chain: str, keep: str) -> dict[str, Any]:
    """The state with the field counters the 2026-09-14 generator computed."""
    _, inp = inputs(chain, keep)
    st = state_dict(chain, keep)
    lo, hi = inp.window.lo, inp.window.hi
    metas = [
        m for m in inp.read.metas
        if m.get("from_block") is not None and m["to_block"] <= hi and m["from_block"] >= lo - 2000
    ]  # fmt: skip
    skip: Counter[str] = Counter()
    for m in metas:
        skip.update(m.get("skipped") or {})
    found = sum(m.get("settlement_txs_found", 0) for m in metas)
    unscanned = sum(m.get("unscanned_blocks", 0) for m in metas)
    return dict(st, txs=[None] * found, n_found=len(inp.windowed.rows), skip=dict(skip),
                failed_ranges=[(0, unscanned - 1)] if unscanned else [])  # fmt: skip


def published_levels(chain: str) -> list[tuple[str, str]]:
    return [(c["level"], c["label"]) for c in run_json(chain)["checks"]]


def check_levels(rep: dict[str, Any]) -> list[tuple[str, str]]:
    return [("pass" if c["level"] == "ok" else c["level"], c["label"]) for c in rep["checks"]]


def diff(published: str, rebuilt: str) -> list[str]:
    return [
        line
        for line in difflib.unified_diff(published.split("\n"), rebuilt.split("\n"), n=0, lineterm="")
        if line[:1] in "+-" and not line.startswith(("+++", "---"))
    ]


@pytest.mark.parametrize("chain", CHAINS)
def test_evidence_is_the_recorded_evidence(chain: str) -> None:
    assert EVIDENCE_ROOT is not None
    for e in run_json(chain)["evidence"]:
        p = EVIDENCE_ROOT / e["path"]
        assert p.is_file(), f"missing {p}"
        assert (record.sha256_file(p), record.count_lines(p)) == (e["sha256"], e["lines"]), e["path"]


@pytest.mark.parametrize("chain", CHAINS)
def test_screen_is_byte_identical_under_the_september_rules(chain: str) -> None:
    st = with_september_field_rule(chain, "last")
    assert field_counts(st) == SEPTEMBER_FIELD[chain]
    rep, rebuilt = screen(chain, "last", st)
    assert rebuilt == published_screen(chain), "\n".join(diff(published_screen(chain), rebuilt))
    assert rep["verdict"] == run_json(chain)["verdict"]


@pytest.mark.parametrize("chain", CHAINS)
def test_generator_field_rule_moves_only_the_field_lines(chain: str) -> None:
    st = state_dict(chain, "last")
    assert field_counts(st) == GENERATOR_FIELD[chain]
    rep, rebuilt = screen(chain, "last", st)
    moved = diff(published_screen(chain), rebuilt)
    assert moved, "the field counters were expected to differ from the published ones"
    assert all(any(k in line for k in FIELD_LINE_MARKERS) for line in moved), "\n".join(moved)
    assert check_levels(rep) == published_levels(chain)


@pytest.mark.parametrize("chain", CHAINS)
def test_default_keep_first_keeps_the_verdict_and_check_levels(chain: str) -> None:
    rep, _ = screen(chain, "first", state_dict(chain, "first"))
    assert rep["verdict"] == run_json(chain)["verdict"]
    assert check_levels(rep) == published_levels(chain)
    assert rep["bids"] == BIDS_KEEP_FIRST[chain]
    assert rep["auctions_attempted"] == run_json(chain)["figures"]["attempted"]
